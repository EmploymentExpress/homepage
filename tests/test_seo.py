"""Guards for the site's discovery layer (sitemap, robots.txt, llms.txt).

Three problems this file is here to prevent:

1. The homepage is a single-page app — its alert board only exists after
   JavaScript fetches ``data/auto-jobs.json``. Crawlers that never run
   JavaScript (Googlebot's secondary pass and the AI answer engines) used to
   get an empty page, and ``sitemap.xml`` listed just two URLs while 500+
   static, canonical alert pages sat undiscoverable in ``share/``.
2. ``robots.txt`` previously said nothing about AI crawlers, so a future
   default-deny policy at the host or CDN level would silently remove the
   site from ChatGPT / Gemini / Perplexity answers.
3. These files are generated by ``scripts/build_seo.py`` on every scheduled
   run. A hand edit would be lost on the next run, so the tests below pin the
   contract the generator must keep satisfying.
"""

